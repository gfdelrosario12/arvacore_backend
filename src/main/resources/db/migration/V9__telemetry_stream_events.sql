-- Migration V9: Dedicated ESP32 Telemetry Notification Stream Schema
-- Stores every individual telemetry transmission received by the backend for real-time streaming, auditing, and debugging.

CREATE TABLE IF NOT EXISTS telemetry_stream_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    node_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    received_at TIMESTAMP NOT NULL,
    device_timestamp TIMESTAMP,
    sequence_number BIGINT,
    field_id BIGINT,
    zone_id BIGINT,
    zone_code VARCHAR(32),
    soil_moisture_percent DOUBLE PRECISION,
    water_level_cm DOUBLE PRECISION,
    water_level_distance_cm DOUBLE PRECISION,
    battery_level DOUBLE PRECISION,
    battery_voltage DOUBLE PRECISION,
    rssi_dbm INTEGER,
    snr_db DOUBLE PRECISION,
    readings_count INTEGER NOT NULL DEFAULT 0,
    status_message VARCHAR(500),
    raw_payload TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_stream_events_received_at ON telemetry_stream_events(received_at DESC);
CREATE INDEX IF NOT EXISTS idx_stream_events_node_time ON telemetry_stream_events(node_id, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_stream_events_field_time ON telemetry_stream_events(field_id, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_stream_events_status ON telemetry_stream_events(status);

