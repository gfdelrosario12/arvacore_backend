CREATE TABLE IF NOT EXISTS system_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    correlation_id VARCHAR(255),
    previous_state VARCHAR(255),
    resulting_state VARCHAR(255),
    payload_json TEXT,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sys_audit_entity_time ON system_audit_logs(entity_type, entity_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sys_audit_event ON system_audit_logs(event_type, created_at DESC);

-- Master System State Table (Single row key: 'SYSTEM')
CREATE TABLE IF NOT EXISTS system_states (
    state_key VARCHAR(50) PRIMARY KEY,
    master_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    notes VARCHAR(500),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO system_states (state_key, master_enabled, updated_by, notes, updated_at)
SELECT 'SYSTEM', TRUE, 'SYSTEM', 'Initial master state: ON', CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM system_states WHERE state_key = 'SYSTEM');

-- Node Pairing Requests Table
CREATE TABLE IF NOT EXISTS node_pairing_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id VARCHAR(255) NOT NULL,
    hardware_model VARCHAR(255),
    firmware_version VARCHAR(100),
    mac_address VARCHAR(100),
    pairing_status VARCHAR(50) NOT NULL,
    rejection_reason VARCHAR(500),
    requested_at TIMESTAMP NOT NULL,
    processed_at TIMESTAMP,
    processed_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_pairing_node_status ON node_pairing_requests(node_id, pairing_status);
CREATE INDEX IF NOT EXISTS idx_pairing_requested_at ON node_pairing_requests(requested_at DESC);
