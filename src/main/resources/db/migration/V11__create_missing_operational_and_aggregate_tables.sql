-- V11: Create missing operational, aggregate, and command history tables
-- Ensures production PostgreSQL schema matches all JPA entities.

-- 1. Zone Telemetry Aggregates
CREATE TABLE IF NOT EXISTS zone_telemetry_aggregates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL,
    field_id BIGINT NOT NULL,
    avg_soil_moisture DOUBLE PRECISION,
    avg_temperature DOUBLE PRECISION,
    avg_humidity DOUBLE PRECISION,
    water_level DOUBLE PRECISION,
    min_battery_voltage DOUBLE PRECISION,
    min_rssi INTEGER,
    min_snr DOUBLE PRECISION,
    total_nodes INTEGER,
    online_nodes INTEGER,
    stale_nodes INTEGER,
    offline_nodes INTEGER,
    health_status VARCHAR(50) NOT NULL,
    calculated_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_zta_zone_calculated ON zone_telemetry_aggregates(zone_id, calculated_at DESC);

-- 2. AWD Threshold Configurations
CREATE TABLE IF NOT EXISTS awd_threshold_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auto_irrigation_config_id BIGINT REFERENCES auto_irrigation_configs(id) ON DELETE CASCADE,
    growth_stage VARCHAR(50) NOT NULL,
    trigger_moisture_percentage DOUBLE PRECISION NOT NULL,
    target_moisture_percentage DOUBLE PRECISION NOT NULL,
    target_flood_depth_cm DOUBLE PRECISION,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

-- 3. Configuration Sync Tasks
CREATE TABLE IF NOT EXISTS config_sync_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edge_node_id BIGINT NOT NULL REFERENCES edge_nodes(id) ON DELETE CASCADE,
    config_version BIGINT NOT NULL,
    correlation_id VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(50) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    max_retries INTEGER NOT NULL DEFAULT 3,
    failure_reason VARCHAR(1000),
    last_synced_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

-- 4. Downlink Queue Items
CREATE TABLE IF NOT EXISTS downlink_queue_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edge_node_id BIGINT NOT NULL REFERENCES edge_nodes(id) ON DELETE CASCADE,
    correlation_id VARCHAR(255) NOT NULL,
    payload_json TEXT NOT NULL,
    f_port INTEGER NOT NULL DEFAULT 10,
    confirmed BOOLEAN NOT NULL DEFAULT TRUE,
    retry_count INTEGER NOT NULL DEFAULT 0,
    max_retries INTEGER NOT NULL DEFAULT 3,
    status VARCHAR(50) NOT NULL,
    last_attempt_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

-- 5. Irrigation Command Records
CREATE TABLE IF NOT EXISTS irrigation_command_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correlation_id VARCHAR(255) NOT NULL UNIQUE,
    command_type VARCHAR(100) NOT NULL,
    target_field_id BIGINT,
    node_id BIGINT,
    current_state VARCHAR(50) NOT NULL,
    actor_source VARCHAR(100),
    rationale VARCHAR(1000),
    failure_reason VARCHAR(1000),
    edge_ack_metrics VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

-- 6. Command State Transition Histories
CREATE TABLE IF NOT EXISTS command_state_transition_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correlation_id VARCHAR(255) NOT NULL,
    from_state VARCHAR(50),
    to_state VARCHAR(50) NOT NULL,
    actor_source VARCHAR(100),
    transition_reason VARCHAR(1000),
    metadata_json VARCHAR(2000),
    timestamp TIMESTAMP NOT NULL
);

