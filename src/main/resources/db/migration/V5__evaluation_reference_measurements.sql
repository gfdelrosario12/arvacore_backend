-- Migration V5: Reference Measurements and Calibration Logs for Performance Evaluation

CREATE TABLE IF NOT EXISTS evaluation_reference_measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_type VARCHAR(50) NOT NULL, -- 'WATER_LEVEL' or 'SOIL_MOISTURE'
    node_id VARCHAR(100) NOT NULL,
    monitoring_zone_id BIGINT,
    reported_value DOUBLE PRECISION NOT NULL,
    reference_value DOUBLE PRECISION NOT NULL,
    absolute_error DOUBLE PRECISION NOT NULL,
    percentage_error DOUBLE PRECISION,
    accuracy_percentage DOUBLE PRECISION,
    measurement_unit VARCHAR(50) NOT NULL,
    instrument_details VARCHAR(255),
    notes VARCHAR(500),
    measured_by VARCHAR(100) NOT NULL,
    measured_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_eval_ref_indicator_node ON evaluation_reference_measurements(indicator_type, node_id, measured_at DESC);
CREATE INDEX IF NOT EXISTS idx_eval_ref_measured_at ON evaluation_reference_measurements(measured_at DESC);

