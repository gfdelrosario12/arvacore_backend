-- Migration V13: Device Authentication Contract and Persistent Node Pairing Bridge
-- Implements ARVA-HMAC-V1 device credentials, anti-replay nonces, and pairing state transitions.

CREATE TABLE IF NOT EXISTS device_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id VARCHAR(255) NOT NULL UNIQUE,
    bootstrap_key_id VARCHAR(255) NOT NULL,
    bootstrap_secret VARCHAR(255) NOT NULL,
    operational_key_id VARCHAR(255),
    operational_secret VARCHAR(255),
    credential_state VARCHAR(50) NOT NULL DEFAULT 'BOOTSTRAP',
    installation_id VARCHAR(255) NOT NULL DEFAULT 'default',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dev_cred_node ON device_credentials(node_id);
CREATE INDEX IF NOT EXISTS idx_dev_cred_boot_key ON device_credentials(bootstrap_key_id);
CREATE INDEX IF NOT EXISTS idx_dev_cred_oper_key ON device_credentials(operational_key_id);

CREATE TABLE IF NOT EXISTS device_auth_nonces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id VARCHAR(255) NOT NULL,
    nonce VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_dev_nonce_node ON device_auth_nonces(node_id, nonce);
CREATE INDEX IF NOT EXISTS idx_dev_nonce_expires ON device_auth_nonces(expires_at);

-- Enhance node_pairing_requests with bridge metadata
ALTER TABLE node_pairing_requests ADD COLUMN IF NOT EXISTS device_key_id VARCHAR(255);
ALTER TABLE node_pairing_requests ADD COLUMN IF NOT EXISTS installation_id VARCHAR(255) DEFAULT 'default';
ALTER TABLE node_pairing_requests ADD COLUMN IF NOT EXISTS operational_key_id VARCHAR(255);
ALTER TABLE node_pairing_requests ADD COLUMN IF NOT EXISTS provisioning_token VARCHAR(255);
ALTER TABLE node_pairing_requests ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

